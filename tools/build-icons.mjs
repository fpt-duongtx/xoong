// Builds everything generated from the icon sources (packages/icons/src/svg, the SVG files on a 24px grid):
//   packages/icons/src/icons.json        every icon as data (name, category, tags, the SVGs): what index.js and the library page read
//   packages/icons/src/icons.css         the whole set as CSS masks: regular, fill and bold, plus the old `.ic[data-ic]` API
//   design/brand-kit/css/icons.css       the part of it the Mist stylesheet carries: the icons `.ic[data-ic]` always had, regular only
//   <block> in controls.css, richtext.css, xoong.css   the icons that package draws itself, between the `icons:start` and `icons:end` markers
//   site/src/icons-data.js, site/src/icons-full.css  what the icon library page loads (the SVGs, in all three weights, load only when one is downloaded)
//   node tools/build-icons.mjs          write them (they are committed)
//   node tools/build-icons.mjs --check  fail when a file on disk differs from what the sources produce (test/icons.test.mjs does this)
// Why a block per package: a control is usable with its own stylesheet alone, without the Mist skin and without installing @xoong/icons; the block holds
// only the icons its sources name, found by `scan` (the same function the `xoong-icons` tool uses for a project).
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { buildCss, scan, svgOf, VARIANTS } from '../packages/icons/src/index.js';

const root = new URL('../', import.meta.url);
const at = (p) => new URL(p, root);
const read = (p) => readFileSync(at(p), 'utf8');

/** What `.ic[data-ic]` used to be called, where the name changed (a class `xi-bold` is the weight, so the icon is text-bold). */
export const LEGACY_RENAMES = { bold: 'text-bold', italic: 'text-italic', underline: 'text-underline', file: 'page' };
/** Every name `.ic[data-ic]` knew: the Mist stylesheet keeps them working. */
export const LEGACY_NAMES = ['chevron-down', 'chevron-up', 'chevron-left', 'chevron-right', 'arrow-up', 'arrow-down', 'arrow-left', 'arrow-right', 'pause', 'play', 'heading', 'paragraph', 'sort', 'close', 'check', 'plus', 'minus', 'search', 'filter', 'menu', 'more', 'grip', 'trash', 'edit', 'copy', 'download', 'external-link', 'link', 'expand', 'undo', 'redo', 'bold', 'italic', 'underline', 'list-bullet', 'list-number', 'quote', 'code', 'bell', 'settings', 'home', 'chart', 'mail', 'star', 'shield', 'zap', 'globe', 'upload', 'users', 'lock', 'image', 'calendar', 'user', 'eye-off', 'eye', 'info', 'warning', 'error', 'success', 'palette', 'sun', 'moon', 'grid', 'file', 'layers', 'sliders'];
/** The packages that draw icons themselves: [stylesheet, the sources it scans, its cascade layer]. */
export const BLOCKS = [
  ['packages/controls/src/controls.css', ['packages/controls/src'], 'xoong-controls'],
  ['packages/richtext/src/richtext.css', ['packages/richtext/src'], 'xoong-richtext'],
  ['packages/ui/src/xoong.css', ['packages/ui/src'], 'xoong.components'],
];
const START = '/* icons:start (generated by tools/build-icons.mjs from packages/icons: the icons this package draws itself; do not edit) */';
const END = '/* icons:end */';

const svgFiles = (dir) => readdirSync(at(dir)).filter((f) => f.endsWith('.svg')).map((f) => f.slice(0, -4)).sort();
const svgText = (p) => read(p).replace(/\r?\n$/, '');

/** The icons as data, from the SVG files and meta.json. */
export function iconData() {
  const meta = JSON.parse(read('packages/icons/src/meta.json'));
  const icons = {};
  for (const name of svgFiles('packages/icons/src/svg')) {
    const m = meta[name];
    if (!m) throw new Error(`icon "${name}" has no entry in packages/icons/src/meta.json`);
    icons[name] = { category: m.category, tags: m.tags, regular: svgText(`packages/icons/src/svg/${name}.svg`) };
    if (existsSync(at(`packages/icons/src/svg/fill/${name}.svg`))) icons[name].fill = svgText(`packages/icons/src/svg/fill/${name}.svg`);
  }
  return { icons, legacy: LEGACY_RENAMES, legacyNames: LEGACY_NAMES };
}

const sourcesOf = (dirs) => dirs.flatMap((d) => readdirSync(at(d), { recursive: true }).filter((f) => /\.(js|mjs|css)$/.test(f)).map((f) => read(`${d}/${f}`).replace(/\/\* icons:start[\s\S]*?\/\* icons:end \*\//, ''))).join('\n');

/** The block for one stylesheet: the icons its package's sources name (regular, plus fill/bold when a `xi-fill` / `xi-bold` appears). */
export function blockFor(dirs, layer) {
  const r = scan(sourcesOf(dirs));
  const css = buildCss({ names: r.names, variants: r.variants, layer });
  return `${START}\n${css}${END}\n`;
}

/** Every generated file: `{ file, text }`. */
export function build() {
  const data = iconData();
  const files = [{ file: 'packages/icons/src/icons.json', text: JSON.stringify(data, null, 1) + '\n' }];
  // from here on use the data just built, not the committed copy that index.js imported
  const names = Object.keys(data.icons);
  const full = `/* The whole xoong icon set as CSS masks (generated by tools/build-icons.mjs: do not edit). Needs img-src data: in a strict CSP.\n   <i class="xi xi-edit"></i>  <i class="xi xi-fill xi-edit"></i>  <i class="xi xi-bold xi-edit"></i>   Load it before other stylesheets: it sits in the lowest layer. */\n${buildCss({ names, legacy: true, layer: 'xoong-icons' })}`;
  files.push({ file: 'packages/icons/src/icons.css', text: full });
  files.push({ file: 'site/src/icons-full.css', text: full });
  const core = LEGACY_NAMES.map((n) => LEGACY_RENAMES[n] ?? n).filter((n, i, a) => a.indexOf(n) === i);
  files.push({ file: 'design/brand-kit/css/icons.css', text: `/* The icons of the Mist stylesheet: the names \`.ic[data-ic]\` always had, regular weight, and the \`xi\` classes for them (generated by tools/build-icons.mjs: do not edit).\n   The whole set, with fill and bold, is @xoong/icons. */\n${buildCss({ names: core, variants: ['regular'], legacy: true })}` });
  const weights = Object.fromEntries(names.map((n) => [n, Object.fromEntries(VARIANTS.map((v) => [v, svgOf(n, v)]))]));
  files.push({ file: 'site/src/icons-data.js', text: `// The SVG of every icon in each weight, for the download buttons of the icon library page (generated by tools/build-icons.mjs: do not edit).\nexport default ${JSON.stringify(weights)};\n` });
  for (const [file, dirs, layer] of BLOCKS) {
    const text = read(file), block = blockFor(dirs, layer);
    const i = text.indexOf(START), j = text.indexOf(END);
    files.push({ file, text: i < 0 ? `${text.replace(/\n*$/, '\n')}\n${block}` : text.slice(0, i) + block + text.slice(j + END.length).replace(/^\n/, '') });
  }
  return files;
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  const check = process.argv.includes('--check');
  const stale = [];
  for (const { file, text } of build()) {
    const same = existsSync(at(file)) && read(file) === text;
    if (!same) { if (check) stale.push(file); else writeFileSync(at(file), text); }
  }
  if (check && stale.length) { console.error(`icon files out of date: ${stale.join(', ')}. Run: node tools/build-icons.mjs`); process.exit(1); }
  if (!check) console.log('wrote the icon data, the stylesheets and the blocks of the packages');
}
